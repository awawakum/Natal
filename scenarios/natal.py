from __future__ import annotations

from datetime import date

from llm_client import generate_reply

# (месяц_начала, день_начала) -> знак; знак действует до следующей даты в списке
ZODIAC_RANGES = [
    ((1, 20), "Водолей"),
    ((2, 19), "Рыбы"),
    ((3, 21), "Овен"),
    ((4, 20), "Телец"),
    ((5, 21), "Близнецы"),
    ((6, 21), "Рак"),
    ((7, 23), "Лев"),
    ((8, 23), "Дева"),
    ((9, 23), "Весы"),
    ((10, 23), "Скорпион"),
    ((11, 22), "Стрелец"),
    ((12, 22), "Козерог"),
]


def parse_birth_date(raw: str) -> date | None:
    """Принимает DD.MM.YYYY, пробует также YYYY-MM-DD на случай другого формата."""
    raw = raw.strip()
    for fmt in ("%d.%m.%Y", "%Y-%m-%d", "%d/%m/%Y"):
        try:
            from datetime import datetime

            return datetime.strptime(raw, fmt).date()
        except ValueError:
            continue
    return None


def sun_sign(birth_date: date) -> str:
    md = (birth_date.month, birth_date.day)
    sign = ZODIAC_RANGES[-1][1]  # Козерог по умолчанию (конец декабря)
    for (start_month, start_day), zodiac in ZODIAC_RANGES:
        if md >= (start_month, start_day):
            sign = zodiac
    return sign


async def build_natal_reply(birth_date: date) -> str:
    sign = sun_sign(birth_date)

    prompt = f"""Дата рождения: {birth_date.strftime('%d.%m.%Y')}
Знак Солнца: {sign}

Сделай бережный разбор на русском языке:
1. Дай короткий общий портрет.
2. Назови 3 сильные стороны и 1 возможную зону роста.
3. Покажи, как это может проявляться в работе и отношениях.
4. Дай один практический совет.
5. Честно уточни, что сейчас рассчитан только знак Солнца; точные время и
место рождения нужны для Асцендента и домов. Спроси, хочет ли пользователь
продолжить, без давления и обещаний точности.

Не выдавай астрологию за научный диагноз, не делай категоричных выводов и не
приписывай пользователю факты, которых нет в запросе."""

    return await generate_reply(
        system_prompt=(
            "Ты — тёплый, проницательный астролог-консультант. Пиши ясно, "
            "человечно и конкретно, без клише и категоричных прогнозов. "
            "Используй короткие абзацы и подзаголовки. 8-12 предложений."
        ),
        user_prompt=prompt,
    )


async def build_chart_photo_reply(
    birth_date: date,
    chart_data: dict[str, str],
    chart_observation: str,
) -> str:
    prompt = f"""Пользователь указал дату рождения: {birth_date.strftime('%d.%m.%Y')}.
Данные, распознанные на изображении натальной карты:
- дата: {chart_data.get('date', 'unknown')}
- время: {chart_data.get('time', 'unknown')}
- место: {chart_data.get('place', 'unknown')}

Наблюдение по изображению:
{chart_observation}

Начни бережный разбор именно по этой карте. Сначала коротко скажи, что удалось
увидеть, затем объясни основные акценты карты простым языком. Если время или
место неизвестны, честно скажи, что точность домов и Асцендента ограничена.
Не выдумывай положения планет, которых нет на изображении, не ставь диагнозов
и не делай категоричных предсказаний. Заверши одним мягким вопросом."""
    return await generate_reply(
        system_prompt=(
            "Ты — внимательная астрологическая консультантка и ИИ-гадалка. "
            "Опирайся только на видимые данные карты и данные пользователя. "
            "Говори по-русски тепло, ясно и без технической перегрузки. "
            "Не выдавай предположения за факт."
        ),
        user_prompt=prompt,
    )
