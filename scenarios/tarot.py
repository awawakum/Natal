def _image_slug(card_name: str) -> str:
    replacements = {
        "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e",
        "ё": "e", "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k",
        "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
        "с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts",
        "ч": "ch", "ш": "sh", "щ": "shch", "ъ": "", "ы": "y", "ь": "",
        "э": "e", "ю": "yu", "я": "ya",
    }
    transliteration = card_name.lower()
    for source, target in replacements.items():
        transliteration = transliteration.replace(source, target)
    return "".join(char if char.isascii() and char.isalnum() else "-" for char in transliteration).strip("-")


