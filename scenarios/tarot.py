def draw_cards(n: int = 3) -> list[tuple[str, str]]:
    """Честный случайный выбор карт без повторов."""
    return random.sample(TAROT_DECK, k=n)


def get_card_image_path(card_name: str) -> Path | None:
    filename = CARD_IMAGE_FILES.get(card_name)
    if filename is None:
        return None
    image_path = CARD_IMAGE_DIR / filename
    return image_path if image_path.is_file() else None


async def build_tarot_reply(
    topic: str,
    question: str,
    cards: list[tuple[str, str]],
) -> str:
    topic_title = TOPIC_TITLES.get(topic, "текущую ситуацию")
    cards_desc = "\n".join(
        f"- {position}: {name} — {meaning}"
        for position, (name, meaning) in zip(CARD_POSITIONS, cards)
    )

    prompt = f"""Вопрос пользователя: «{question}»
Тема: {topic_title}

Карты и фиксированные позиции:
{cards_desc}

Составь ответ на русском языке в таком порядке:
1. Коротко назови общий мотив расклада.
2. Отдельно объясни ситуацию, совет и итог, связывая каждую позицию с картой.
3. Дай один практический мягкий шаг, который пользователь может сделать.
4. Заверши одним естественным вопросом по теме.

Не обещай неизбежное будущее, не запугивай и не выдумывай значения карт.
Не повторяй вопрос дословно и не предлагай купить услугу."""

    return await generate_reply(
        system_prompt=(
            "Ты — тёплая, проницательная гадалка. Пиши по-русски живо, "
            "человечно и конкретно, будто внимательно слушаешь человека. "
            "Связывай трактовку с вопросом и каждой картой, не используй "
            "клише и категоричные предсказания. Дай мягкий практический "
            "совет и один вопрос для продолжения диалога. Используй короткие "
            "абзацы и заголовки позиций. Не превращай ответ в карьерную, "
            "техническую или психологическую инструкцию: не упоминай Git, "
            "код, стек, резюме, вакансии и другие инструменты. 8-12 предложений."
        ),
        user_prompt=prompt,
    )
