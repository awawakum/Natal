"""Предохранитель для явных попыток злоупотребить ботом.

Фильтр блокирует не «неудобные» вопросы, а запросы на раскрытие внутренней
механики, обход оплаты/лимитов, подмену инструкций и технические атаки.
"""
import re


PROBE_PATTERNS = (
    r"(докажи|проверь|проверить|тестир|сломать|сломай|взломать).{0,40}(бот|гадал|модель|систем|лимит|отказ)",
    r"(ты\s+настоящая|ты\s+реальная|это\s+точно\s+гадалка|работаешь\s+как\s+бот)",

    # Prompt injection и подмена роли.
    r"игнорируй\s+(предыдущ|системн|инструкц)",
    r"(забудь|отмени|отбрось)\s+(все\s+)?(предыдущ|системн|правил|ограничен)",
    r"(новая|моя)\s+системн(ая|ые)\s+(инструкц|правил)",
    r"(ты\s+теперь|считай\s+себя|притворись|представься).{0,50}(админ|разработчик|режим|другой\s+модель)",
    r"(jailbreak|prompt\s*injection|developer\s+message|system\s+message)",
    r"(ignore|disregard|forget)\s+(all\s+)?(previous|system|your)\s+(instructions|rules|prompt)",
    r"(show|reveal|print)\s+(your\s+)?(system\s+prompt|hidden\s+instructions|api\s+key|source\s+code)",

    # Запросы внутренних данных и секретов.
    r"(покажи|выведи|раскрой|напечатай|скажи).{0,40}(промпт|инструкц|системн|исходник|код|конфиг|секрет|токен|api\s*key|парол)",
    r"(env|\.env|bot[_\s-]?token|llm[_\s-]?api|api[_\s-]?key|secret[_\s-]?key)",
    r"(какая|какой)\s+(модель|провайдер|url|ключ)\s+(использу|установ|настро)",

    # Обход коммерческих ограничений и начислений.
    r"(обойди|обойти|сбрось|сними|накрути|добавь).{0,40}(лимит|блок|запрос|баланс|оплат|кредит)",
    r"(дай|начисли|зачисли).{0,30}(бесплатн|платн|запрос).{0,20}(без\s+оплат|даром|бесплатно)",
    r"(подделай|сымитируй|фальшив).{0,30}(платеж|чек|webhook|оплат)",
    r"(покажи|дай)\s+(как\s+)?(обойти|взломать)\s+(оплату|лимит)",

    # Явные технические попытки атаковать приложение или базу.
    r"(drop|delete|truncate|update|insert)\s+(table|database|balances|payments|users)",
    r"(sql\s*инъекц|инъекц|execute\s+запрос|выполни\s+код|запусти\s+команду)",
    r"(доступ|подключение)\s+к\s+(базе|серверу|админке|файлам)",
    r"(curl|wget|powershell|cmd\.exe|subprocess|os\.system|eval\s*\(|exec\s*\()",
)


def should_temporarily_block(text: str) -> bool:
    normalized = " ".join(text.lower().split())
    return any(re.search(pattern, normalized) for pattern in PROBE_PATTERNS)